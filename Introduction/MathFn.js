// JavaScript provides a built-in Math object that provides a set of methods to perform mathematical operations.

// Examples:
console.log("Math.round(5.8) is:", Math.round(5.8)); // 6 (rounds to nearest integer)
console.log("Math.round(5.1) is:", Math.round(5.1)); // 5 (rounds down to nearest integer)
console.log("Math.floor(5.8) is:", Math.floor(5.8)); // 5 (rounds down to nearest integer)
console.log("Math.ceil(5.8) is:", Math.ceil(5.8)); // 6 (rounds up to nearest integer)
console.log("Math.ceil(5.1) is:", Math.ceil(5.1)); // 6 (rounds up to nearest integer)
console.log("Math.abs(-5) is:", Math.abs(-5)); // 5 (absolute value)
console.log("Math.sqrt(25) is:", Math.sqrt(25)); // 5 (square root)
console.log("Math.pow(2, 3) is:", Math.pow(2, 3)); // 8 (2 raised to the power of 3)
console.log("Math.max(1, 2, 3) is:", Math.max(1, 2, 3)); // 3 (maximum value)
console.log("Math.min(1, 2, 3) is:", Math.min(1, 2, 3)); // 1 (minimum value)
console.log("Math.random() is:", Math.random()); // Generates random number between 0 and 1 Eg -> 0.12387387836789
console.log("Math.random() * 6 is:", Math.random() * 6); // Generates random number between 0 and 6 Eg -> 0.12387387836789 * 10 = 4.2387387836789
console.log("Math.floor(Math.random() * 6) is:", Math.floor(Math.random() * 6)); // Generates random integer between 0 and 5 Eg -> 5.2387387836789 = (Ans) -> 5
console.log("Math.PI is:", Math.PI); // 3.141592653589793 (value of pi)
console.log("Math.E is:", Math.E); // 2.718281828459045 (value of e)
console.log("Math.sin(0) is:", Math.sin(0)); // 0 (sine of 0 radians)
console.log("Math.cos(0) is:", Math.cos(0)); // 1 (cosine of 0 radians)
console.log("Math.tan(0) is:", Math.tan(0)); // 0 (tangent of 0 radians)
console.log("Math.log(10) is:", Math.log(10)); // 2.302585092994046 (natural logarithm of 10)
console.log("Math.log10(100) is:", Math.log10(100)); // 2 (base 10 logarithm of 100)
console.log("Math.log2(8) is:", Math.log2(8)); // 3 (base 2 logarithm of 8)
console.log("Math.exp(1) is:", Math.exp(1)); // 2.718281828459045 (e raised to the power of 1)
console.log("Math.sign(-5) is:", Math.sign(-5)); // -1 (indicates negative number)
console.log("Math.sign(0) is:", Math.sign(0)); // 0 (indicates zero)
console.log("Math.sign(5) is:", Math.sign(5)); // 1 (indicates positive number)
console.log("Math.trunc(5.8) is:", Math.trunc(5.8)); // 5 (truncates decimal part)
console.log("Math.trunc(-5.8) is:", Math.trunc(-5.8)); // -5 (truncates decimal part)
